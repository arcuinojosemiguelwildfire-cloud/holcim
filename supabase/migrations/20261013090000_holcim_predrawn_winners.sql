-- Holcim Event System - pre-drawn winner reveal.
-- PostgreSQL twin of MySQL migration 035_create_predrawn_winners.sql: the same
-- columns, keys and rules, so the MySQL -> PostgreSQL import copies rows 1:1.
-- Winners chosen outside this system (Spin the Wheel) are assigned to letters
-- A-Z per event day and revealed on the LED screen. Separate from the
-- Minor / Major Randomizer (randomizer_draws is not touched).
-- MySQL's generated live_lock + UNIQUE keys become partial unique indexes on
-- the rows that are not voided.

create table public.predrawn_winners (
  id            integer generated by default as identity primary key,
  event_id      integer not null,
  event_day_id  integer not null,
  letter        varchar(1) not null,
  attendee_id   integer not null,
  prize_label   varchar(150),
  assigned_by   integer references public.users (id) on delete set null on update cascade,
  assigned_at   timestamptz not null default now(),
  revealed_at   timestamptz,
  revealed_by   integer references public.users (id) on delete set null on update cascade,
  voided_at     timestamptz,
  voided_by     integer references public.users (id) on delete set null on update cascade,
  void_reason   varchar(200),
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now(),
  constraint chk_predrawn_winners_letter check (letter ~ '^[A-Z]$'),
  constraint chk_predrawn_winners_void_after_reveal check (voided_at is null or revealed_at is not null),
  constraint fk_predrawn_winners_day_event foreign key (event_day_id, event_id)
    references public.event_days (id, event_id) on delete restrict on update restrict,
  constraint fk_predrawn_winners_attendee_event foreign key (attendee_id, event_id)
    references public.attendees (id, event_id) on delete restrict on update restrict
);
create unique index uq_predrawn_winners_day_letter on public.predrawn_winners (event_day_id, letter) where voided_at is null;
create unique index uq_predrawn_winners_day_attendee on public.predrawn_winners (event_day_id, attendee_id) where voided_at is null;
create index idx_predrawn_winners_attendee_event on public.predrawn_winners (attendee_id, event_id);
create index idx_predrawn_winners_event on public.predrawn_winners (event_id);
create index idx_predrawn_winners_assigned_by on public.predrawn_winners (assigned_by);
create index idx_predrawn_winners_revealed_by on public.predrawn_winners (revealed_by);
create index idx_predrawn_winners_voided_by on public.predrawn_winners (voided_by);
create index fk_predrawn_winners_day_event on public.predrawn_winners (event_day_id, event_id);
create trigger trg_predrawn_winners_updated_at before update on public.predrawn_winners
  for each row execute function public.set_updated_at();

-- ---------------------------------------------------------------- security (same rules as Phase 1 / 2)
-- RLS on; clients may only SELECT, and only admin + event operator (the PHP
-- routes GET /predrawn are open to the same two roles). No write policies.
alter table public.predrawn_winners enable row level security;
do $$
declare
  r text;
begin
  foreach r in array array['anon', 'authenticated'] loop
    if exists (select 1 from pg_roles where rolname = r) then
      execute format('revoke all on public.predrawn_winners from %I', r);
      execute format('revoke all on all sequences in schema public from %I', r);
    end if;
  end loop;
  if exists (select 1 from pg_roles where rolname = 'authenticated') then
    execute 'grant select on public.predrawn_winners to authenticated';
    execute 'create policy predrawn_winners_select_randomizer on public.predrawn_winners
      for select to authenticated using ((select private.can_operate_randomizers()))';
  end if;
end $$;
