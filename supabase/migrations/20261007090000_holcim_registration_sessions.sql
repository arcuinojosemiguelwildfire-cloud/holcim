-- Holcim Event System - registration sessions (Phase 10).
-- PostgreSQL twin of MySQL migration 033_create_registration_sessions.sql:
-- the same tables, columns, keys and rules, so the MySQL -> PostgreSQL import
-- copies them 1:1. See that file and docs/REGISTRATION_SESSIONS.md.
--
-- An event day has one or more registration sessions; an attendee (one
-- record, one QR) registers once per session. Eligibility is derived from
-- these rows: Minor = an active registration in ANY session of the day,
-- Major = an active registration in a session with counts_for_major.
-- Times are Asia/Manila wall-clock time (start_time is a plain "time").

-- ---------------------------------------------------------------- registration_sessions
create table public.registration_sessions (
  id                integer generated by default as identity primary key,
  event_id          integer not null,
  event_day_id      integer not null,
  label             varchar(100) not null,
  session_date      date not null,
  start_time        time,                       -- Asia/Manila wall time; null = not scheduled (legacy default)
  description       varchar(255),
  sort_order        smallint not null default 1 check (sort_order >= 0),
  is_enabled        boolean not null default true,
  counts_for_major  boolean not null default true,
  is_current        boolean not null default false,
  created_at        timestamptz not null default now(),
  updated_at        timestamptz not null default now(),
  constraint uq_registration_sessions_id_day unique (id, event_day_id),
  constraint chk_registration_sessions_current_enabled check (not is_current or is_enabled),
  constraint fk_registration_sessions_day_event foreign key (event_day_id, event_id)
    references public.event_days (id, event_id) on delete restrict on update restrict
);
-- MySQL utf8mb4_unicode_ci made the label unique per day case-insensitively.
create unique index uq_registration_sessions_day_label on public.registration_sessions (event_day_id, lower(label));
-- MySQL: generated current_lock = IF(is_current, event_day_id, NULL) + UNIQUE -> one current session per day.
create unique index uq_registration_sessions_one_current on public.registration_sessions (event_day_id) where is_current;
create index idx_registration_sessions_day_order on public.registration_sessions (event_day_id, sort_order);
create index idx_registration_sessions_event on public.registration_sessions (event_id);
create index fk_registration_sessions_day_event on public.registration_sessions (event_day_id, event_id);
create trigger trg_registration_sessions_updated_at before update on public.registration_sessions
  for each row execute function public.set_updated_at();

-- ---------------------------------------------------------------- session_registrations
-- One row per attendee per session; never deleted by the application
-- (removal = status 'removed'; every change is in session_registration_changes).
create table public.session_registrations (
  id                       integer generated by default as identity primary key,
  event_id                 integer not null,
  event_day_id             integer not null,
  registration_session_id  integer not null,
  attendee_id              integer not null,
  status                   text not null default 'active' check (status in ('active', 'removed')),
  source                   text not null check (source in ('scan', 'manual')),
  registered_at            timestamptz not null default now(),
  registered_by            integer references public.users (id) on delete set null on update cascade,
  removed_at               timestamptz,
  removed_by               integer references public.users (id) on delete set null on update cascade,
  removal_reason           varchar(200),
  created_at               timestamptz not null default now(),
  updated_at               timestamptz not null default now(),
  constraint uq_session_registrations_attendee_session unique (attendee_id, registration_session_id),
  constraint fk_session_registrations_session_day foreign key (registration_session_id, event_day_id)
    references public.registration_sessions (id, event_day_id) on delete restrict on update cascade,
  constraint fk_session_registrations_attendee_event foreign key (attendee_id, event_id)
    references public.attendees (id, event_id) on delete restrict on update cascade,
  constraint fk_session_registrations_day_event foreign key (event_day_id, event_id)
    references public.event_days (id, event_id) on delete restrict on update cascade
);
create index idx_session_registrations_day_status on public.session_registrations (event_day_id, status, attendee_id);
create index idx_session_registrations_session_status on public.session_registrations (registration_session_id, status, registered_at);
create index idx_session_registrations_attendee_event on public.session_registrations (attendee_id, event_id);
create index idx_session_registrations_registered_by on public.session_registrations (registered_by);
create index idx_session_registrations_removed_by on public.session_registrations (removed_by);
create index fk_session_registrations_session_day on public.session_registrations (registration_session_id, event_day_id);
create index fk_session_registrations_day_event on public.session_registrations (event_day_id, event_id);
create trigger trg_session_registrations_updated_at before update on public.session_registrations
  for each row execute function public.set_updated_at();

-- ---------------------------------------------------------------- session_registration_changes (append-only)
create table public.session_registration_changes (
  id                       bigint generated by default as identity primary key,
  session_registration_id  integer not null references public.session_registrations (id) on delete restrict on update cascade,
  event_id                 integer not null references public.events (id) on delete restrict on update restrict,
  action                   text not null check (action in ('scanned', 'manually_added', 'restored', 'removed')),
  status_after             text not null check (status_after in ('active', 'removed')),
  performed_by             integer references public.users (id) on delete set null on update cascade,
  reason                   varchar(200),
  created_at               timestamptz not null default now()
);
create index idx_session_registration_changes_registration on public.session_registration_changes (session_registration_id, created_at);
create index idx_session_registration_changes_event on public.session_registration_changes (event_id);
create index idx_session_registration_changes_performed_by on public.session_registration_changes (performed_by);

-- ---------------------------------------------------------------- scan_logs
alter table public.scan_logs
  add column registration_session_id integer references public.registration_sessions (id) on delete set null on update cascade;
create index idx_scan_logs_session on public.scan_logs (registration_session_id);
alter table public.scan_logs drop constraint scan_logs_result_check;
alter table public.scan_logs add constraint scan_logs_result_check
  check (result in ('registered', 'already_registered', 'invalid_qr', 'wrong_event', 'attendee_inactive', 'registration_removed'));

-- ---------------------------------------------------------------- backfill (same as MySQL 033)
-- Only does something if event data already exists here (e.g. imported at
-- MySQL migration 032). For a fresh import from MySQL 033+ these tables are
-- empty and the import copies the MySQL rows with their ids.
insert into public.registration_sessions
  (event_id, event_day_id, label, session_date, start_time, description, sort_order, is_enabled, counts_for_major, is_current)
select d.event_id, d.id, 'Registration', d.event_date, null,
       'Created automatically for registrations made before registration sessions existed.', 1, true, true, true
from public.event_days d
where not exists (select 1 from public.registration_sessions s where s.event_day_id = d.id);

insert into public.session_registrations
  (event_id, event_day_id, registration_session_id, attendee_id, status, source, registered_at, registered_by, created_at, updated_at)
select r.event_id, r.event_day_id, s.id, r.attendee_id, 'active', 'scan', r.scanned_at, r.scanner_user_id, r.created_at, r.created_at
from public.registration_scans r
join public.registration_sessions s on s.event_day_id = r.event_day_id and s.is_current
where not exists (
  select 1 from public.session_registrations x
  where x.attendee_id = r.attendee_id and x.registration_session_id = s.id
);

-- ---------------------------------------------------------------- security baseline (same as Phase 1)
alter table public.registration_sessions enable row level security;
alter table public.session_registrations enable row level security;
alter table public.session_registration_changes enable row level security;
do $$
declare
  r text;
begin
  foreach r in array array['anon', 'authenticated'] loop
    if exists (select 1 from pg_roles where rolname = r) then
      execute format('revoke all on public.registration_sessions, public.session_registrations, public.session_registration_changes from %I', r);
      execute format('revoke all on all sequences in schema public from %I', r);
    end if;
  end loop;
end $$;
