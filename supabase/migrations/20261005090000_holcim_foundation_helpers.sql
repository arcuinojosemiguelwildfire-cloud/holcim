create schema if not exists extensions;
-- Supabase already provides pgcrypto in the "extensions" schema; this is a no-op there.
create extension if not exists pgcrypto with schema extensions;

-- The application's time zone. MySQL DATETIME values were written as Manila
-- wall-clock time (the PHP API set the MySQL session time_zone to the PHP
-- offset, Asia/Manila = UTC+08:00, no DST since 1978). In PostgreSQL every
-- point in time is a timestamptz; local dates/times are derived explicitly
-- with "AT TIME ZONE public.app_time_zone()".
create or replace function public.app_time_zone()
returns text
language sql
immutable
parallel safe
set search_path = ''
as $$ select 'Asia/Manila'::text $$;

comment on function public.app_time_zone() is
  'Holcim business time zone. Use (ts AT TIME ZONE public.app_time_zone()) for local display/dates.';

-- Replacement for MySQL "ON UPDATE CURRENT_TIMESTAMP": refresh updated_at when
-- a row changes, unless the UPDATE set updated_at explicitly (same rule as
-- MySQL, e.g. QR regeneration sets updated_at itself).
create or replace function public.set_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if new.updated_at is not distinct from old.updated_at and new is distinct from old then
    new.updated_at := now();
  end if;
  return new;
end;
$$;

-- New attendee QR tokens: 24 cryptographically secure random bytes,
-- base64url without padding = exactly 32 characters of [A-Za-z0-9_-].
-- Identical format to the PHP App\Utils\Token::random(24). Existing tokens
-- are imported as data and are never regenerated by this function.
create or replace function public.generate_qr_token()
returns text
language sql
volatile
set search_path = ''
as $$
  select translate(rtrim(encode(extensions.gen_random_bytes(24), 'base64'), '='), '+/', '-_')
$$;

comment on function public.generate_qr_token() is
  '24 random bytes as base64url (32 chars). Same format as the PHP Token::random(24).';
