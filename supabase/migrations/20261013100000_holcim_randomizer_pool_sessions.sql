-- Holcim Event System - Randomizer pool sessions.
-- PostgreSQL twin of MySQL migration 036_create_randomizer_pool_sessions.sql:
-- the registration sessions whose registered attendees form the Randomizer's
-- name pool, per event day. Composite foreign keys keep each selected session
-- on the same event day (and event) as the row. Configuration only.

create table public.randomizer_pool_sessions (
  id                       integer generated by default as identity primary key,
  event_id                 integer not null,
  event_day_id             integer not null,
  registration_session_id  integer not null,
  selected_by              integer references public.users (id) on delete set null on update cascade,
  selected_at              timestamptz not null default now(),
  constraint uq_randomizer_pool_sessions_day_session unique (event_day_id, registration_session_id),
  constraint fk_randomizer_pool_sessions_day_event foreign key (event_day_id, event_id)
    references public.event_days (id, event_id) on delete restrict on update restrict,
  constraint fk_randomizer_pool_sessions_session_day foreign key (registration_session_id, event_day_id)
    references public.registration_sessions (id, event_day_id) on delete restrict on update restrict
);
create index idx_randomizer_pool_sessions_session_day on public.randomizer_pool_sessions (registration_session_id, event_day_id);
create index idx_randomizer_pool_sessions_event on public.randomizer_pool_sessions (event_id);
create index idx_randomizer_pool_sessions_selected_by on public.randomizer_pool_sessions (selected_by);
create index fk_randomizer_pool_sessions_day_event on public.randomizer_pool_sessions (event_day_id, event_id);

-- ---------------------------------------------------------------- security (same rules as Phase 1 / 2)
-- RLS on; clients may only SELECT, admin + event operator (GET /predrawn). No write policies.
alter table public.randomizer_pool_sessions enable row level security;
do $$
declare
  r text;
begin
  foreach r in array array['anon', 'authenticated'] loop
    if exists (select 1 from pg_roles where rolname = r) then
      execute format('revoke all on public.randomizer_pool_sessions from %I', r);
      execute format('revoke all on all sequences in schema public from %I', r);
    end if;
  end loop;
  if exists (select 1 from pg_roles where rolname = 'authenticated') then
    execute 'grant select on public.randomizer_pool_sessions to authenticated';
    execute 'create policy randomizer_pool_sessions_select_randomizer on public.randomizer_pool_sessions
      for select to authenticated using ((select private.can_operate_randomizers()))';
  end if;
end $$;
